const bible = readFileSync(join(ROOT, 'BIBLE.md'), 'utf8');
const table = bible.slice(bible.indexOf('## 10. Tags'), bible.indexOf('## 11.'));
const icons: Record<string, string> = existsSync(join(ROOT, 'drafts', 'tag-icons.json'))
  ? JSON.parse(readFileSync(join(ROOT, 'drafts', 'tag-icons.json'), 'utf8'))
  : {};
mkdirSync(join(ROOT, 'tags'), { recursive: true });
let count = 0;
for (const m of table.matchAll(/^\| `([a-z0-9-]+)` \| ([^|]+) \|\s*([^|]*?)\s*\|$/gm)) {
  const [, id, title, synonyms] = m as unknown as [string, string, string, string];
  const description = DESCRIPTIONS[id];
  if (!description) throw new Error(`no description for ${id}`);
  const fields: Record<string, unknown> = { title: title.trim() };
  const list = synonyms.split(',').map((s) => s.trim()).filter(Boolean);
  if (list.length) fields.synonyms = list;
  if (icons[id]) fields.icon = icons[id];
  writeFileSync(join(ROOT, 'tags', `${id}.md`), `---\n${stringify(fields, { lineWidth: 0 })}---\n\n${description}\n`);
  count++;
}
console.log(`${count} tags`);
